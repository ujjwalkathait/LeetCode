class Solution {
public:
    int minMoves(vector<int>& nums) {
        // [3,1,9,10,2] -> [4,2,10,10,3] -> [5,3,11,10,4] -> [6,4,11,11,5] -> [7,5,12,11,6] -> [8,6,12,12,7] -> [9,7,13,12,8] -> [10,8,13,13,9] -> [11,9,14,13,10] -> [12,10,14,14,11] -> [13,11,15,14,12] -> [14,12,15,15,13] ->[15,13,16,15,14] ->[16,14,16,16,15] -> [17,15,16,17,16] -> [17,16,17,18,17] -> [18,17,18,18,18] -> [19,18,18,19,19] -> [19,19,19,20,20] -> [20,20,20,20,21] -> [21,21,21,21,21]

        int mini = *min_element(nums.begin(), nums.end());
        int ans = 0;
        for(int x : nums){
            ans += (x-mini);
        }
        return ans;
    }
};